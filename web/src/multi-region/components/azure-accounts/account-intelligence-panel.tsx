/* ------------------------------------------------------------------ */
/*  Section G — PRT (Primary Refresh Token) presence                   */
/* ------------------------------------------------------------------ */
/*
 * Browsers cannot read the `x-ms-RefreshTokenCredential` cookie that
 * carries the PRT — it is httpOnly and scoped to `login.microsoftonline.com`,
 * so the inspector is INDIRECT. We probe by:
 *
 *   1. Creating a hidden iframe whose `src` is the AAD authorize endpoint
 *      with `prompt=none&response_mode=query`, `client_id` = Azure CLI
 *      (a public first-party that accepts any redirect inside its
 *      allow-list), and a `redirect_uri` pointing back at the dev server.
 *   2. On the dev-server side the WebUI serves whatever lands at `/`,
 *      so the iframe will navigate to `<origin>/?code=...` (success) or
 *      `<origin>/?error=interaction_required` (no usable PRT).
 *   3. Once the iframe finishes navigating, we read its location and
 *      derive success / failure.
 *
 * Subtleties:
 *   - The iframe's final URL is same-origin (since the redirect_uri is the
 *     dev-server origin), so the `load` event handler CAN read
 *     `iframe.contentWindow.location.href`. AAD's intermediate page is
 *     cross-origin (`login.microsoftonline.com`), so the FIRST `load`
 *     event we see may throw a SecurityError on read — that's expected,
 *     we just wait for the next one.
 *   - We DO NOT use `postMessage` from the redirect target because the
 *     redirect target is the SPA's own index.html — we don't want to
 *     ship a separate hosted endpoint just for this probe. Reading the
 *     iframe URL directly works because the URL becomes same-origin once
 *     AAD has issued its 302 back.
 *   - A 5-second timeout guards against PRT-absent cases where AAD shows
 *     its login UI inside the iframe instead of redirecting. The iframe
 *     stays cross-origin in that case and we never get a readable URL.
 *
 * Result interpretation:
 *   - `code=...` in query → PRT exists and SSO works for this client.
 *   - `error=interaction_required` / `login_required` → PRT missing or
 *     stale; user would need to re-sign-in to refresh it.
 *   - Other error / timeout → "Unable to determine".
 *
 * Important limitation: this is browser-only. There is no DPAPI / TPM
 * access from JS so we cannot read the PRT itself. The probe is
 * specifically "can AAD silently issue a token via prompt=none?", which
 * is a useful PROXY for "does the PRT exist and route to this browser?"
 * but is not authoritative — e.g. CA policies that require step-up MFA
 * on every issuance will surface as `interaction_required` even though
 * the PRT is fine.
 */

type PrtProbeStatus =
  | "idle"
  | "probing"
  | "working"
  | "broken"
  | "unable";

interface PrtProbeResult {
  status: PrtProbeStatus;
  detail: string;
  /** Wall-clock when the probe ended, for "last checked" rendering. */
  endedAt?: number;
}

/**
 * Azure CLI client id — same public app used elsewhere in this file's
 * codebase for ARM access. Accepts redirect URIs on the dev-server
 * `localhost:*` allow-list when registered as a public client.
 */
const PRT_PROBE_CLIENT_ID = "04b07795-8ddb-461a-bbee-02f9e1bf7b46";
const PRT_PROBE_TIMEOUT_MS = 5000;

/**
 * Build the authorize URL used by the iframe probe. Mirror the parameter
 * set MSAL.js would send for an ARM `.default` silent acquire, plus
 * `prompt=none` so AAD never shows UI.
 */
function buildPrtProbeAuthorizeUrl(loginHint: string): string {
  const redirectUri =
    typeof window !== "undefined"
      ? `${window.location.origin}/`
      : "http://localhost/";
  const params = new URLSearchParams({
    response_type: "code",
    client_id: PRT_PROBE_CLIENT_ID,
    scope: "https://management.azure.com/.default",
    response_mode: "query",
    prompt: "none",
    redirect_uri: redirectUri,
  });
  if (loginHint) params.set("login_hint", loginHint);
  // `nonce` is required for `id_token` flows; not needed for code flow
  // but some AAD edge cases still demand it. Cheap to include.
  params.set(
    "nonce",
    `azbm-prt-probe-${Math.random().toString(36).slice(2)}`,
  );
  return `https://login.microsoftonline.com/common/oauth2/v2.0/authorize?${params.toString()}`;
}

/**
 * Drive the iframe probe. Resolves with the final probe status — never
 * rejects. The iframe is removed from the DOM before this returns.
 */
function probePrtPresence(loginHint: string): Promise<PrtProbeResult> {
  return new Promise<PrtProbeResult>((resolve) => {
    if (typeof document === "undefined") {
      resolve({
        status: "unable",
        detail: "Running outside a browser — no DOM available.",
        endedAt: Date.now(),
      });
      return;
    }
    const url = buildPrtProbeAuthorizeUrl(loginHint);
    const iframe = document.createElement("iframe");
    iframe.setAttribute("aria-hidden", "true");
    iframe.setAttribute("tabindex", "-1");
    iframe.style.position = "absolute";
    iframe.style.width = "1px";
    iframe.style.height = "1px";
    iframe.style.opacity = "0";
    iframe.style.pointerEvents = "none";
    iframe.style.border = "0";
    iframe.referrerPolicy = "no-referrer";

    let settled = false;
    const cleanup = (): void => {
      if (timeoutId) clearTimeout(timeoutId);
      iframe.onload = null;
      if (iframe.parentNode) iframe.parentNode.removeChild(iframe);
    };
    const finish = (result: PrtProbeResult): void => {
      if (settled) return;
      settled = true;
      cleanup();
      resolve({ ...result, endedAt: Date.now() });
    };

    const timeoutId = window.setTimeout(() => {
      finish({
        status: "unable",
        detail:
          "No same-origin redirect within the timeout window. AAD likely tried to render its login UI inside the iframe (which we can't read cross-origin). Most often this means the PRT is absent or your tenant requires step-up.",
      });
    }, PRT_PROBE_TIMEOUT_MS);

    iframe.onload = (): void => {
      // The first `load` event will throw on cross-origin URL access
      // (AAD landing page). Once AAD redirects back to our origin the
      // subsequent `load` will succeed. We can't tell apart "still on
      // AAD" vs "finished" without try/catch.
      let finalUrl: string;
      try {
        finalUrl = iframe.contentWindow?.location.href ?? "";
      } catch {
        // Still on a cross-origin page (login.microsoftonline.com) —
        // wait for the next load. If AAD never redirects back the
        // timeout above fires.
        return;
      }
      if (!finalUrl) return;

      let parsed: URL;
      try {
        parsed = new URL(finalUrl);
      } catch {
        finish({
          status: "unable",
          detail: `Iframe ended at an unparseable URL: ${finalUrl}`,
        });
        return;
      }

      // Read params from both query string AND hash — some flows use
      // fragment-mode even when we asked for query.
      const qs = parsed.searchParams;
      const hash = new URLSearchParams(
        parsed.hash.startsWith("#") ? parsed.hash.slice(1) : parsed.hash,
      );
      const code = qs.get("code") ?? hash.get("code");
      const error = qs.get("error") ?? hash.get("error");

      if (code) {
        finish({
          status: "working",
          detail:
            "AAD redirected back with an authorization code — `prompt=none` succeeded, so the browser holds a working PRT cookie (or an equivalent SSO artifact) for this client.",
        });
        return;
      }
      if (error) {
        const known = error === "interaction_required" || error === "login_required";
        finish({
          status: known ? "broken" : "unable",
          detail: known
            ? `AAD returned \`error=${error}\` — no usable PRT. The browser must re-authenticate the user before silent SSO can succeed again.`
            : `AAD returned \`error=${error}\`. This is not the standard interaction-required outcome — most often a CA policy or tenant config issue.`,
        });
        return;
      }
      finish({
        status: "unable",
        detail: `Iframe finished at ${parsed.origin}${parsed.pathname} but no \`code\` or \`error\` parameter was present.`,
      });
    };

    document.body.appendChild(iframe);
    iframe.src = url;
  });
}

