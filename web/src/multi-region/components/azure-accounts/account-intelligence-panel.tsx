type AudienceBucket = "arm" | "graph" | "batch" | "unknown";

function classifyAudience(rawAud: string): AudienceBucket {
  const a = (rawAud ?? "").toLowerCase();
  if (
    a.includes("management.azure.com") ||
    a.includes("management.core.windows.net") ||
    a === "797f4846-ba00-4fd7-ba43-dac1f8f63013"
  ) {
    return "arm";
  }
  if (
    a.includes("graph.microsoft.com") ||
    a === "00000003-0000-0000-c000-000000000000"
  ) {
    return "graph";
  }
  if (
    a.includes("batch.core.windows.net") ||
    a === "ddbf3205-c6bd-46ae-8127-60eb93363864"
  ) {
    return "batch";
  }
  return "unknown";
}

function audienceBadgeVariant(
  audience: AudienceBucket,
): "success" | "info" | "warning" | "secondary" {
  if (audience === "arm") return "success";
  if (audience === "graph") return "info";
  if (audience === "batch") return "warning";
  return "secondary";
}

function audienceLabel(audience: AudienceBucket): string {
  if (audience === "arm") return "ARM";
  if (audience === "graph") return "Graph";
  if (audience === "batch") return "Batch";
  return "Other";
}

/**
 * Resolve the active tenant id for an account across the three sources of
 * truth (per-account override → msal-cached → home).
 */
function resolveActiveTenantId(acct: AzureLoginAccount): string {
  return (
    acct.activeTenantId ??
    getActiveTenant(acct.homeAccountId) ??
    acct.tenantId
  );
}

/**
 * Pull the domain out of a UPN or mail address. Returns the empty
 * string when the value doesn't look like an email.
 */
function domainFromAddress(value: string | undefined | null): string {
  if (!value) return "";
  const at = value.lastIndexOf("@");
  if (at < 0) return "";
  return value.slice(at + 1).toLowerCase();
}

/**
 * Detect whether a UPN looks like a B2B guest (has the `#EXT#@` marker)
 * AND whether the home-tenant suffix differs from the mail suffix.
 */
interface AccountTypeFingerprint {
  type: "Member" | "Guest" | "External" | "Unknown";
  reason: string;
  /** UPN-side domain (what AAD recorded). */
  upnDomain: string;
  /** Mail-side domain (what the user actually owns). */
  mailDomain: string;
  /** True when the UPN matches the `…#EXT#@…` B2B pattern. */
  hasExtMarker: boolean;
}

function fingerprintAccountType(
  account: AzureLoginAccount,
  tenants: TenantInfo[] | undefined,
  meResponse: GraphMeResponse | null,
): AccountTypeFingerprint {
  const upn = account.username ?? "";
  const upnDomain = domainFromAddress(upn);
  const mail = meResponse?.mail ?? null;
  const mailDomain = domainFromAddress(mail);
  const hasExtMarker = /#ext#@/i.test(upn);

  // Graph's own `userType` claim is the canonical answer when we got it.
  const userType = meResponse?.userType?.toLowerCase();
  if (userType === "guest") {
    return {
      type: "Guest",
      reason:
        "Microsoft Graph reports userType = Guest. The account was invited to this tenant from another directory.",
      upnDomain,
      mailDomain,
      hasExtMarker,
    };
  }
  if (userType === "member" && !hasExtMarker) {
    return {
      type: "Member",
      reason:
        "Microsoft Graph reports userType = Member and the UPN is native to the tenant.",
      upnDomain,
      mailDomain,
      hasExtMarker,
    };
  }

  // Fall back to UPN-pattern heuristics when /me failed or returned
  // partial data.
  if (hasExtMarker) {
    return {
      type: "Guest",
      reason:
        "UPN contains the B2B `#EXT#@` marker AAD appends to invited accounts. The mail domain shown is the user's home directory.",
      upnDomain,
      mailDomain,
      hasExtMarker,
    };
  }

  // Find the home tenant's default domain to compare against the UPN.
  const homeTenant = tenants?.find((t) => t.tenantId === account.tenantId);
  const homeDomain = (homeTenant?.defaultDomain ?? "").toLowerCase();
  if (
    homeDomain &&
    upnDomain &&
    !upnDomain.endsWith(homeDomain) &&
    !homeDomain.endsWith(upnDomain) &&
    upnDomain !== homeDomain
  ) {
    return {
      type: "External",
      reason: `UPN domain (${upnDomain}) does not match the home tenant's default domain (${homeDomain}). May be a federated account or a guest whose UPN was rewritten.`,
      upnDomain,
      mailDomain,
      hasExtMarker,
    };
  }
  if (
    mailDomain &&
    upnDomain &&
    mailDomain !== upnDomain
  ) {
    return {
      type: "External",
      reason: `Mail domain (${mailDomain}) differs from UPN domain (${upnDomain}). The account likely originated elsewhere.`,
      upnDomain,
      mailDomain,
      hasExtMarker,
    };
  }
  return {
    type: "Member",
    reason:
      "UPN does not contain a B2B marker and the mail / UPN domains agree. Best-effort heuristic — Microsoft Graph `/me` did not return a definitive `userType`.",
    upnDomain,
    mailDomain,
    hasExtMarker,
  };
}

interface SyncSourceFingerprint {
  source: "Cloud-only" | "On-prem synced" | "Unknown";
  reason: string;
  lastSyncIso?: string;
}

function fingerprintSyncSource(
  meResponse: GraphMeResponse | null,
): SyncSourceFingerprint {
  if (!meResponse) {
    return {
      source: "Unknown",
      reason:
        "Microsoft Graph `/me` did not return data — the panel cannot read `onPremisesSyncEnabled`. Re-acquire the Graph token if this persists.",
    };
  }
  if (meResponse.onPremisesSyncEnabled === true) {
    return {
      source: "On-prem synced",
      reason:
        "Graph reports `onPremisesSyncEnabled = true` — the account is mastered in on-premises Active Directory and synced via Entra Connect.",
      lastSyncIso: meResponse.onPremisesLastSyncDateTime ?? undefined,
    };
  }
  if (
    meResponse.onPremisesSyncEnabled === false ||
    meResponse.onPremisesSyncEnabled == null
  ) {
    return {
      source: "Cloud-only",
      reason:
        "Graph did not report `onPremisesSyncEnabled = true` — the account is mastered in Entra ID directly (no Entra Connect mirror).",
    };
  }
  return {
    source: "Unknown",
    reason: "Unexpected value for onPremisesSyncEnabled.",
  };
}

/**
 * Subset of `/me` fields this panel cares about. Kept narrow so we can
 * pull only what we need (`$select`) and so the typing is stable when
 * AAD adds new fields.
 */
interface GraphMeResponse {
  id?: string;
  userPrincipalName?: string;
  mail?: string | null;
  userType?: string;
  onPremisesSyncEnabled?: boolean | null;
  onPremisesLastSyncDateTime?: string | null;
  onPremisesImmutableId?: string | null;
  accountEnabled?: boolean;
  givenName?: string | null;
  surname?: string | null;
  preferredLanguage?: string | null;
}

async function probeGraphMe(
  tenantId: string,
  accessToken: string,
): Promise<GraphMeResponse> {
  const select = [
    "id",
    "userPrincipalName",
    "mail",
    "userType",
    "onPremisesSyncEnabled",
    "onPremisesLastSyncDateTime",
    "onPremisesImmutableId",
    "accountEnabled",
    "givenName",
    "surname",
    "preferredLanguage",
  ].join(",");
  const url = `https://graph.microsoft.com/v1.0/me?$select=${select}`;
  const resp = await fetch(url, {
    headers: {
      Authorization: `Bearer ${accessToken}`,
      Accept: "application/json",
    },
  });
  if (!resp.ok) {
    let detail = `${resp.status}`;
    try {
      const body = (await resp.json()) as {
        error?: { message?: string };
      };
      if (body.error?.message) detail = `${resp.status}: ${body.error.message}`;
    } catch {
      /* body not JSON — ignore */
    }
    throw new Error(`Graph /me failed: ${detail}`);
  }
  const data = (await resp.json()) as Record<string, unknown>;
  return {
    id: typeof data.id === "string" ? data.id : undefined,
    userPrincipalName:
      typeof data.userPrincipalName === "string"
        ? data.userPrincipalName
        : undefined,
    mail:
      typeof data.mail === "string"
        ? data.mail
        : data.mail === null
          ? null
          : undefined,
    userType: typeof data.userType === "string" ? data.userType : undefined,
    onPremisesSyncEnabled:
      typeof data.onPremisesSyncEnabled === "boolean"
        ? data.onPremisesSyncEnabled
        : data.onPremisesSyncEnabled === null
          ? null
          : undefined,
    onPremisesLastSyncDateTime:
      typeof data.onPremisesLastSyncDateTime === "string"
        ? data.onPremisesLastSyncDateTime
        : null,
    onPremisesImmutableId:
      typeof data.onPremisesImmutableId === "string"
        ? data.onPremisesImmutableId
        : null,
    accountEnabled:
      typeof data.accountEnabled === "boolean"
        ? data.accountEnabled
        : undefined,
    givenName: typeof data.givenName === "string" ? data.givenName : null,
    surname: typeof data.surname === "string" ? data.surname : null,
    preferredLanguage:
      typeof data.preferredLanguage === "string"
        ? data.preferredLanguage
        : null,
  };
}

/**
 * Format a unix-epoch-seconds value as "in 14m" / "12m ago", with a
 * tooltip-friendly absolute fallback. Returns "—" on invalid input.
 */
function formatEpoch(value: number | undefined): string {
  if (!value || !Number.isFinite(value)) return "—";
  const deltaMs = value * 1000 - Date.now();
  const absMin = Math.abs(Math.round(deltaMs / 60_000));
  const direction = deltaMs >= 0 ? "in" : "ago";
  if (absMin < 1) return "now";
  if (absMin < 60) return `${direction === "in" ? "in " : ""}${absMin}m${direction === "ago" ? " ago" : ""}`;
  const absHr = Math.round(absMin / 60);
  if (absHr < 24)
    return `${direction === "in" ? "in " : ""}${absHr}h${direction === "ago" ? " ago" : ""}`;
  const absDay = Math.round(absHr / 24);
  return `${direction === "in" ? "in " : ""}${absDay}d${direction === "ago" ? " ago" : ""}`;
}

function isoFromEpoch(value: number | undefined): string {
  if (!value || !Number.isFinite(value)) return "Unknown";
  try {
    return new Date(value * 1000).toISOString();
  } catch {
    return "Unknown";
  }
}

